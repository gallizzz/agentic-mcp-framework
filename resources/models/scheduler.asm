	main rule r_Main = 
		if state=INIT then
		par
			forall $c in Compartment do
			 	par
			 		skipNextPill($c):=false	 
			 		setNewTime($c):=false
			 	endpar
			state:=NORMAL
		endpar
		else
		par 
		 tempComputation:=computeDer
		 r_NORMAL_FUNCT[]
		endpar
	endif
		
