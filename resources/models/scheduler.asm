	// NEW: helper predicates for proactive same-day rescheduling.
	// All times are minutes since midnight; clinical windows are trusted inputs.
	function agentTargetValid =
		(agentTargetDoseIndex >= drugIndex(agentTargetCompartment) and
		 agentTargetDoseIndex < iton(length(time_consumption(agentTargetCompartment))))

	function agentWindowValid =
		(clinicalEarliestTime <= clinicalLatestTime and
		 clinicalLatestTime < 1440n and
		 patientAvailableFrom <= agentGoalLatestTime)

	function agentReactiveEvent =
		(exist $c in Compartment with (isPillMissed($c) or pillTakenWithDelay($c))) or
		(rtoi(pillboxSystemTime/1440n) > day)

	function effectiveDoseTime($c in Compartment, $j in Natural) =
		if ($j < drugIndex($c) and at(actual_time_consumption($c),$j) != 0n) then
			at(actual_time_consumption($c),$j)
		else
			at(time_consumption($c),$j)
		endif

	function agentTimeDistance($x in Natural, $y in Natural) =
		if $x >= $y then $x-$y else $y-$x endif

	// Check all slots, not only next(compartment): M2 may involve two
	// different doses in the same compartment. Earlier doses with a recorded
	// actual intake are checked against their actual intake times.
	function agentTimeAdmissible($t in Natural) =
		($t >= (pillboxSystemTime mod 1440n) and
		 $t >= clinicalEarliestTime and $t <= clinicalLatestTime and
		 $t >= patientAvailableFrom and $t <= agentGoalLatestTime and
		 (forall $c in Compartment with
			(forall $j in range(0n, iton(length(time_consumption($c)))) with
				(($c = agentTargetCompartment and $j = agentTargetDoseIndex) or
				 ($j < drugIndex($c) and at(actual_time_consumption($c),$j) = 0n) or
				 ($t != effectiveDoseTime($c,$j) and
					(($t < effectiveDoseTime($c,$j) and
					  effectiveDoseTime($c,$j)-$t >= ntoi(minToInterferer(name(agentTargetCompartment),name($c))))
					 or
					 ($t > effectiveDoseTime($c,$j) and
					  $t-effectiveDoseTime($c,$j) >= ntoi(minToInterferer(name($c),name(agentTargetCompartment))))))))))

	// Search in ascending time order. Equal distances keep the earlier time.
	// All iterations occur within the current ASM step (seq/while).
	rule r_FindClosestCorrection =
		seq
			par
				repairScanTime := clinicalEarliestTime
				repairBestTime := 0n
				repairBestDistance := 0
				repairFound := false
			endpar
			while repairScanTime <= clinicalLatestTime do
				seq
					if agentTimeAdmissible(repairScanTime) then
						let ($distance = agentTimeDistance(repairScanTime,agentRequestedTime)) in
							if not repairFound or $distance < repairBestDistance then
								par
									repairBestTime := repairScanTime
									repairBestDistance := $distance
									repairFound := true
								endpar
							endif
						endlet
					endif
					repairScanTime := repairScanTime + 1n
				endseq
		endseq

	rule r_rescheduler = 
	  forall $compartment in Compartment do 
	  par
	  	if isPillMissed($compartment) then //M
		  	par
		  		setNewTime ($compartment):= true
				//Missed pill check if the new time causes invariant violation
				 if ((forall $c in next($compartment) with 
				   	(  (iton((at(time_consumption($c),drugIndex($c)) - 
				   		at(time_consumption($compartment),drugIndex($compartment))-ntoi(deltaDelay(name($compartment)))))
					>= (minToInterferer(name($compartment),name($c))) and $c!=$compartment) or 
					(iton((at(time_consumption($c),nextDrugIndex($c)) - at(time_consumption($compartment),drugIndex($compartment))-
						ntoi(deltaDelay(name($compartment)))
					)) 
					>= (minToInterferer(name($compartment),name($c))) and $c=$compartment)
					))) then //A
				  			par
				  				setOriginalTime ($compartment):= false
				  				newTime ($compartment):= at(time_consumption($compartment),drugIndex($compartment))+deltaDelay(name($compartment))
				  			endpar // if not update new time of pill otherwise skip the pill
					else
					  	par
					  		setOriginalTime ($compartment):= true
					  		newTime ($compartment):= at(time(name($compartment)),drugIndex($compartment))
					  	endpar
					endif
			endpar
		else
			setNewTime ($compartment):= false	
		endif
	 	if pillTakenWithDelay($compartment) then
			//pill taken later compared the timecompartment
			//for all next pills that cause invariant violation because the current has been 
			//taken after set time -> skip pill
			forall $c2 in next($compartment) do 
			   if	(((iton(at(time_consumption($c2),drugIndex($c2)) - (pillboxSystemTime mod 1440n)) //it should be actual_time_consumption, but since it is updated in the next state I use pillboxSystemTime here
				<= (minToInterferer(name($compartment),name($c2)))) and $c2!=$compartment) or 
				((iton(at(time_consumption($c2),nextDrugIndex($c2)) - (pillboxSystemTime mod 1440n))
				<= (minToInterferer(name($compartment),name($c2)))) and $c2=$compartment)
				) then
					par
						skipNextPill($compartment, $c2):= true
						skipNextPill($compartment) := true
					endpar
				// skip next pill -> rule must be in pillbox
				endif
		else
			par
				forall $c3 in next($compartment) do 
					skipNextPill($compartment, $c3):= false
				skipNextPill($compartment) := false
			endpar
		endif
	endpar
	
// Reset all skipPill to false
rule r_resetMidnight =
		if (rtoi(pillboxSystemTime/1440n))> day then
			forall $c in Compartment do
				par
					setNewTime($c) := false 
					skipNextPill($c) := false
					forall $c2 in Compartment with $c!=$c2 do
						skipNextPill ($c, $c2) := false
				endpar
endif
	
	rule r_evaluate_output_pill=
		 forall $compartment in Compartment do 
			 forall $c2 in next($compartment) do 
				 if skipNextPill($compartment) and setNewTime($compartment) and skipNextPill($compartment, $c2) then
					skip
				 endif
	
				
	// NEW: reset the old skip commands while handling an agent request.
	rule r_ClearAgentSkipOutputs =
		forall $c in Compartment do
			par
				skipNextPill($c) := false
				forall $d in Compartment do
					skipNextPill($c,$d) := false
			endpar

	rule r_ClearAllNewTimeCommands =
		forall $c in Compartment do
			par
				setNewTime($c) := false
				agentUpdate($c) := false
			endpar

	rule r_ClearOtherNewTimeCommands($keep in Compartment) =
		forall $c in Compartment with $c != $keep do
			par
				setNewTime($c) := false
				agentUpdate($c) := false
			endpar

	rule r_ClearAllAgentUpdateFlags =
		forall $c in Compartment do agentUpdate($c) := false

	// NEW: evaluation of a proactive LLM-generated rescheduling request.
	// A local replacement is only a candidate until its preview is accepted.
	rule r_EvaluateAgentRequest =
		par
			r_ClearAgentSkipOutputs[]
			hasProcessedAgentRequest := true
			lastProcessedAgentRequestId := agentRequestId
			decisionRequestId := agentRequestId
			if not agentTargetValid then
				par
					r_ClearAllNewTimeCommands[]
					agentDecision := BLOCK
					agentReason := INVALID_TARGET
					previewRequested := false
				endpar
			else
				if agentExpectedScheduleVersion != scheduleVersion then
					par
						r_ClearAllNewTimeCommands[]
						agentDecision := REPLAN
						agentReason := STALE_STATE
						previewRequested := false
					endpar
				else
					if not agentWindowValid then
						par
							r_ClearAllNewTimeCommands[]
							agentDecision := BLOCK
							agentReason := INVALID_WINDOW
							previewRequested := false
						endpar
					else
						if agentTimeAdmissible(agentRequestedTime) then
							par
								r_ClearOtherNewTimeCommands[agentTargetCompartment]
								setNewTime(agentTargetCompartment) := true
								agentUpdate(agentTargetCompartment) := true
								setOriginalTime(agentTargetCompartment) := false
								newTime(agentTargetCompartment) := agentRequestedTime
								targetDoseIndex(agentTargetCompartment) := agentTargetDoseIndex
								commandId(agentTargetCompartment) := agentRequestId
								commandBaseScheduleVersion(agentTargetCompartment) := scheduleVersion
								pendingRequestId := agentRequestId
								pendingCompartment := agentTargetCompartment
								pendingDoseIndex := agentTargetDoseIndex
								pendingCorrectedTime := agentRequestedTime
								pendingScheduleVersion := scheduleVersion
								pendingDecision := ALLOW
								commitWaitSteps := 0n
								agentPhase := AP_WAIT_COMMIT
								agentDecision := NO_DECISION
								agentReason := NO_REASON
								previewRequested := false
							endpar
						else
							seq
								r_FindClosestCorrection[]
								if repairFound then
									par
										r_ClearAllNewTimeCommands[]
										pendingRequestId := agentRequestId
										pendingCompartment := agentTargetCompartment
										pendingDoseIndex := agentTargetDoseIndex
										pendingCorrectedTime := repairBestTime
										pendingScheduleVersion := scheduleVersion
										previewRequestId := agentRequestId
										previewBaseScheduleVersion := scheduleVersion
										previewTargetCompartment := agentTargetCompartment
										previewTargetDoseIndex := agentTargetDoseIndex
										previewCandidateTime := repairBestTime
										previewRequested := true
										agentPhase := AP_WAIT_PREVIEW
										agentDecision := NO_DECISION
										agentReason := NO_REASON
									endpar
								else
									par
										r_ClearAllNewTimeCommands[]
										agentDecision := REPLAN
										agentReason := NO_LOCAL_REPAIR
										previewRequested := false
									endpar
								endif
							endseq
						endif
					endif
				endif
			endif
		endpar

	// NEW: second phase. PreviewCoordinator observes an independent Pillbox
	// instance executed via scripted run(PBPREVIEW) steps; no live update yet.
	rule r_ResolveAgentPreview =
		if scheduleVersion != pendingScheduleVersion or previewTimedOut then
			par
				r_ClearAllNewTimeCommands[]
				r_ClearAgentSkipOutputs[]
				agentDecision := REPLAN
				agentReason := STALE_STATE
				decisionRequestId := pendingRequestId
				previewRequested := false
				agentPhase := AP_IDLE
			endpar
		else
			if previewCompleted and previewResultRequestId = pendingRequestId then
				if previewResultBaseVersion = pendingScheduleVersion and
				   previewOutcome = PREVIEW_COMPATIBLE then
					par
						r_ClearOtherNewTimeCommands[pendingCompartment]
						r_ClearAgentSkipOutputs[]
						setNewTime(pendingCompartment) := true
						agentUpdate(pendingCompartment) := true
						setOriginalTime(pendingCompartment) := false
						newTime(pendingCompartment) := pendingCorrectedTime
						targetDoseIndex(pendingCompartment) := pendingDoseIndex
						commandId(pendingCompartment) := pendingRequestId
						commandBaseScheduleVersion(pendingCompartment) := pendingScheduleVersion
						pendingDecision := REPLACE
						commitWaitSteps := 0n
						agentDecision := NO_DECISION
						agentReason := NO_REASON
						decisionRequestId := pendingRequestId
						previewRequested := false
						agentPhase := AP_WAIT_COMMIT
					endpar
				else
					par
						r_ClearAllNewTimeCommands[]
						r_ClearAgentSkipOutputs[]
						agentDecision := REPLAN
						if previewOutcome = PREVIEW_CONFLICT then
							agentReason := PREVIEW_CONFLICT_REASON
						else
							agentReason := PREVIEW_UNAVAILABLE
						endif
						decisionRequestId := pendingRequestId
						previewRequested := false
						agentPhase := AP_IDLE
					endpar
				endif
			else
				par
					r_ClearAllNewTimeCommands[]
					r_ClearAgentSkipOutputs[]
					previewRequested := false
				endpar
			endif
		endif


    // A decision becomes final only after Pillbox has acknowledged execution.
    // Pending command outputs stay stable during AP_WAIT_COMMIT.
    rule r_WaitForCommit =
        if lastAppliedCommandId(pendingCompartment) = pendingRequestId then
            par
                r_ClearAllNewTimeCommands[]
                agentPhase := AP_IDLE
                agentDecision := pendingDecision
                agentReason := NO_REASON
                decisionRequestId := pendingRequestId
            endpar
        else
            if lastRejectedCommandId(pendingCompartment) = pendingRequestId then
                par
                    r_ClearAllNewTimeCommands[]
                    agentPhase := AP_IDLE
                    agentDecision := REPLAN
                    agentReason := COMMIT_REJECTED
                    decisionRequestId := pendingRequestId
                endpar
            else
                if commitWaitSteps >= 8n then
                    par
                        r_ClearAllNewTimeCommands[]
                        agentPhase := AP_IDLE
                        agentDecision := BLOCK
                        agentReason := COMMIT_TIMEOUT
                        decisionRequestId := pendingRequestId
                    endpar
                else
                    commitWaitSteps := commitWaitSteps + 1n
                endif
            endif
        endif

	// NEW: serialize proactive and existing reactive enforcement.
	// Existing missed/delayed-dose events take priority and invalidate preview.
    rule r_NORMAL_FUNCT =
        if agentPhase = AP_WAIT_COMMIT then
            r_WaitForCommit[]
        else
            if agentReactiveEvent then
                par
                    r_rescheduler[]
                    r_resetMidnight[]
                    r_evaluate_output_pill[]
                    r_ClearAllAgentUpdateFlags[]
                    if agentPhase = AP_WAIT_PREVIEW then
                        par
                            agentPhase := AP_IDLE
                            agentDecision := REPLAN
                            agentReason := REACTIVE_PRIORITY
                            decisionRequestId := pendingRequestId
                            previewRequested := false
                        endpar
                    else
                        if agentRequestPending and
                          (not hasProcessedAgentRequest or agentRequestId != lastProcessedAgentRequestId) then
                            par
                                hasProcessedAgentRequest := true
                                lastProcessedAgentRequestId := agentRequestId
                                decisionRequestId := agentRequestId
                                agentDecision := REPLAN
                                agentReason := REACTIVE_PRIORITY
                                previewRequested := false
                            endpar
                        endif
                    endif
                endpar
            else
                if agentPhase = AP_WAIT_PREVIEW then
                    r_ResolveAgentPreview[]
                else
                    if agentRequestPending and
                       (not hasProcessedAgentRequest or agentRequestId != lastProcessedAgentRequestId) then
                        r_EvaluateAgentRequest[]
                    else
                        par
                            r_rescheduler[]
                            r_resetMidnight[]
                            r_evaluate_output_pill[]
                            r_ClearAllAgentUpdateFlags[]
                            previewRequested := false
                        endpar
                    endif
                endif
            endif
        endif

//If pill is missed and there is no overlap with next pills, delayed it
invariant inv_G_newTime over newTime: (forall $compartment in Compartment with
 	(
 		(forall $c in next($compartment) with 
 			(isPillMissed($compartment) and 
 				((iton((at(time_consumption($c),drugIndex($c)) - 
			at(time_consumption($compartment),drugIndex($compartment))-ntoi(deltaDelay(name($compartment)))		))
		>= (minToInterferer(name($compartment),name($c))) and $c!=$compartment) 
		or (iton((at(time_consumption($c),nextDrugIndex($c)) - at(time_consumption($compartment),drugIndex($compartment))-
			ntoi(deltaDelay(name($compartment))))) 
		>= (minToInterferer(name($compartment),name($c))) and $c=$compartment)))
	 implies ((newTime ($compartment) = at(time_consumption($compartment),drugIndex($compartment))+deltaDelay(name($compartment))))
	 )))


//If pill overlaps with next pills, skip the next pill that overlaps
invariant inv_G_skipNextPill over skipNextPill(Compartment): (forall $compartment in Compartment with
 	(
 		(forall $c in next($compartment) with 
		(pillTakenWithDelay($compartment) and ((iton(at(time_consumption($c),drugIndex($c)) - (pillboxSystemTime mod 1440n)) //it should be actual_time_consumption, but since it is updated in the next state I use pillboxSystemTime here
		<= (minToInterferer(name($compartment),name($c)))) and $c!=$compartment) or 
		((iton(at(time_consumption($c),nextDrugIndex($c)) - (pillboxSystemTime mod 1440n))
		<= (minToInterferer(name($compartment),name($c)))) and $c=$compartment)
		) 
	 implies (skipNextPill($compartment, $c)= true and
						skipNextPill($compartment)= true))))
 


/*For a medication in a given compartment and slot that has been taken, the difference 
between its ACTUAL intake time and the intake time of the subsequent medications 
taken (in the next slot of the same compartment or in another compartment) must be 
greater than or equal to the medication's minToInterferer value with the subsequent medications */
invariant inv_A_actual_time over Compartment: (forall $compartment in Compartment with 
	(forall $c in next($compartment) with 
    	((at(actual_time_consumption($c),drugIndex($c))!= 0n and at(actual_time_consumption($compartment),drugIndex($compartment))!= 0n ) implies
    	(  (iton((at(actual_time_consumption($c),drugIndex($c)) - at(actual_time_consumption($compartment),drugIndex($compartment)))) 
			>= (minToInterferer(name($compartment),name($c))) and $c!=$compartment) or (iton((at(actual_time_consumption($c),nextDrugIndex($c)) - at(actual_time_consumption($compartment),drugIndex($compartment)))) 
			>= (minToInterferer(name($compartment),name($c))) and $c=$compartment)
		))
    ))
	
			
	
